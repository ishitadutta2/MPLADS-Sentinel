def get_lang() -> str:
    return st.session_state.get("lang", "en")


def t(key: str, **kwargs) -> str:
    """Looks up `key` in the active language, falling back to English,
    then to the raw key itself so a missing translation is visible
    (as English text) rather than a blank string."""
    entry = STRINGS.get(key)
    if not entry:
        return key
    s = entry.get(get_lang()) or entry.get("en") or key
    return s.format(**kwargs) if kwargs else s


def stage_label(stage: str) -> str:
    """Display label for a projects.status pipeline value (Recommended,
    Sanctioned, Work In Progress, Payment Released, Completed) —
    translates how it's *shown*, while every comparison/filter in the
    code keeps using the plain English value stored in the database."""
    return t(f"stage_{stage}") if f"stage_{stage}" in STRINGS else stage


def risk_label(band: str) -> str:
    """Display label for a LOW/MEDIUM/HIGH/CRITICAL risk_band value, for
    the handful of places (plain st.dataframe calls) that show the band
    as text rather than through risk_pill()'s coloured HTML badge."""
    return t(f"risk_{band}") if f"risk_{band}" in STRINGS else band


def language_switcher(compact: bool = False):
    """Renders the :material/language: language selector. Uses the ambient `st`, so it
    works wherever it's called from — a sidebar container or, as of the
    header redesign, a column in the top header row. `compact=True`
    hides the visible label (used in the header, where space is tight)
    and relies on the help tooltip instead."""
    codes = list(LANGUAGES.keys())
    labels = list(LANGUAGES.values())
    current = get_lang()
    idx = codes.index(current) if current in codes else 0
    choice = st.selectbox(
        f":material/language: {t('language')}", labels, index=idx, key="_lang_switch",
        label_visibility="collapsed" if compact else "visible",
        help="Translates this app's own screens. Data typed in by users (e.g. work descriptions) "
             "stays in whichever language it was entered in — same as the real eSAKSHI portal.",
    )
    new_code = codes[labels.index(choice)]
    if new_code != current:
        st.session_state.lang = new_code
        st.rerun()
